import Foundation
import Zlib
import zlib

let options = BenchmarkOptions(arguments: Array(CommandLine.arguments.dropFirst()))

func seconds(_ duration: Duration) -> Double {
  let components = duration.components
  return Double(components.seconds) + Double(components.attoseconds) / 1e18
}

func measure(iterations: Int, _ operation: () throws -> Int) rethrows -> Double {
  var observedBytes = 0
  let elapsed = try ContinuousClock().measure {
    for _ in 0..<iterations { observedBytes += try operation() }
  }
  precondition(observedBytes > 0)
  return seconds(elapsed)
}

func median(_ values: [Double]) -> Double {
  let sorted = values.sorted()
  return (sorted[(sorted.count - 1) / 2] + sorted[sorted.count / 2]) / 2
}

func compare(
  iterations: Int, swift: () throws -> Int, c: () throws -> Int
) rethrows -> (swift: Double, c: Double) {
  var swiftTimes: [Double] = []
  var cTimes: [Double] = []
  for sample in 0..<options.samples {
    // Alternate which implementation goes first between samples.
    if sample.isMultiple(of: 2) {
      swiftTimes.append(try measure(iterations: iterations, swift))
      cTimes.append(try measure(iterations: iterations, c))
    } else {
      cTimes.append(try measure(iterations: iterations, c))
      swiftTimes.append(try measure(iterations: iterations, swift))
    }
  }
  return (median(swiftTimes), median(cTimes))
}

func verify(_ decoded: borrowing UniqueArray<UInt8>, matches input: [UInt8]) {
  precondition(decoded.count == input.count && input.indices.allSatisfy { decoded[$0] == input[$0] })
}

var results: [BenchmarkResult] = []
for inputBytes in [65_536, 64 * 1_048_576, 128 * 1_048_576] {
  for payload in BenchmarkPayload.allCases {
    let input = payload.input(count: inputBytes)
    let iterations = options.iterations(for: input.count)
    FileHandle.standardError.write(
      Data("Benchmarking \(payload.rawValue), \(input.count) bytes, \(iterations) calls/sample\n".utf8))
    for (strategyName, strategy, cLevel, cStrategy) in [
      ("automatic", ZLib.Strategy.automatic, Int32(6), Z_DEFAULT_STRATEGY),
      ("stored", .stored, Z_NO_COMPRESSION, Z_DEFAULT_STRATEGY),
      ("fixed", .fixed, Int32(6), Z_FIXED),
      ("dynamic", .dynamic, Int32(6), Z_DEFAULT_STRATEGY)
    ] {
      let swiftEncoded = try ZLib.deflate(input: input.span, strategy: strategy)
      let cEncoded = cZlibDeflate(input.span, level: cLevel, strategy: cStrategy)
      // Check both encoders with both decoders before timing.
      verify(try ZLib.inflate(input: swiftEncoded.span), matches: input)
      verify(cZlibInflate(swiftEncoded.span), matches: input)
      verify(try ZLib.inflate(input: cEncoded.span), matches: input)
      verify(cZlibInflate(cEncoded.span), matches: input)

      let encodeTime = try compare(
        iterations: iterations,
        swift: { try ZLib.deflate(input: input.span, strategy: strategy).count },
        c: { cZlibDeflate(input.span, level: cLevel, strategy: cStrategy).count })
      // Feed identical C-generated bytes to both decoders so differences in
      // encoder output do not affect the decode comparison.
      let decodeTime = try compare(
        iterations: iterations,
        swift: { try ZLib.inflate(input: cEncoded.span).count },
        c: { cZlibInflate(cEncoded.span).count })
      let mebibytes = Double(input.count) * Double(iterations) / 1_048_576
      results.append(
        BenchmarkResult(
          payload: payload.rawValue, strategy: strategyName, inputBytes: input.count, iterations: iterations,
          cLevel: cLevel, cStrategy: cStrategy == Z_FIXED ? "Z_FIXED" : "Z_DEFAULT_STRATEGY",
          swiftEncode: mebibytes / encodeTime.swift, cEncode: mebibytes / encodeTime.c,
          swiftDecode: mebibytes / decodeTime.swift, cDecode: mebibytes / decodeTime.c))
    }
  }
}

if options.updateReadme {
  try markdownReport(results, options: options).write(
    to: benchmarkDirectory.appendingPathComponent("README.md"), atomically: true, encoding: .utf8)
  print("Updated Benchmarks/README.md")
} else if options.markdown {
  print(markdownReport(results, options: options), terminator: "")
} else {
  print(
    "payload,strategy,c_level,c_strategy,input_bytes,iterations,swift_encode_mib_s,c_encode_mib_s,encode_swift_over_c,swift_decode_mib_s,c_decode_mib_s,decode_swift_over_c"
  )
  for result in results { print(result.csv) }
}
